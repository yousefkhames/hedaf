// Real-browser click-through. Usage: node tests/e2e.mjs <baseUrl>   (needs puppeteer-core and Chrome)
import puppeteer from 'puppeteer-core';
const base = process.argv[2] || 'http://localhost:8000/';
const b = await puppeteer.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const p = await b.newPage(); const errs = []; let n = 0, bad = 0;
p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true });
p.on('dialog', d => d.accept());
const ok = (name, c) => { n++; if (!c) bad++; console.log((c ? 'PASS ' : 'FAIL ') + name); };
const sleep = ms => new Promise(r => setTimeout(r, ms));
const txt = s => p.$eval(s, e => e.textContent.trim());
const setv = (s, v) => p.$eval(s, (e, v) => { e.value = v; e.dispatchEvent(new Event('input', { bubbles: true })); e.dispatchEvent(new Event('change', { bubbles: true })); }, v);
await p.goto(base, { waitUntil: 'load' }); await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: 'load' }); await sleep(500);
ok('Arabic and RTL by default', await p.$eval('html', h => h.dir === 'rtl' && h.lang === 'ar'));
ok('empty state offers a first goal', !!(await p.$('#emptyAdd')));
await p.click('#emptyAdd'); await sleep(200);
await p.click('#goalSave'); await sleep(150);
ok('empty goal is rejected (error mark)', (await p.$$('#goalModal .err')).length >= 1);
await setv('#fName', 'سيارة'); await setv('#fTarget', '120000'); await setv('#fSaved', '20000');
const d = new Date(Date.now() + 400 * 864e5).toISOString().slice(0, 10); await setv('#fDeadline', d);
await p.click('#goalSave'); await sleep(300);
ok('goal card created', (await p.$$('.card')).length === 1);
ok('weekly need is shown', (await txt('.need')).length > 5);
ok('progress is 17%', (await txt('.gring b')).includes('17'));
await p.click('[data-act="deposit"]'); await sleep(200);
await setv('#txAmount', '5000'); await p.click('#txSave'); await sleep(300);
ok('deposit updates saved amount (25,000)', /25[,٬.]?000|٢٥[,٬.]?٠٠٠/.test(await txt('.gmoney')));
await p.click('[data-act="withdraw"]'); await sleep(200); await setv('#txAmount', '1000'); await p.click('#txSave'); await sleep(300);
ok('withdraw updates saved amount (24,000)', /24[,٬.]?000|٢٤[,٬.]?٠٠٠/.test(await txt('.gmoney')));
await p.click('[data-act="history"]'); await sleep(200);
ok('history lists the deposits', (await p.$eval('#histBody', e => e.children.length)) >= 2); await p.click('#histClose'); await sleep(150);
await p.reload({ waitUntil: 'load' }); await sleep(400);
ok('goal survives reload', (await p.$$('.card')).length === 1 && /24[,٬.]?000|٢٤[,٬.]?٠٠٠/.test(await txt('.gmoney')));
await p.click('#langBtn'); await sleep(300);
ok('English switches to LTR', await p.$eval('html', h => h.dir === 'ltr' && h.lang === 'en'));
ok('no horizontal overflow (390px)', await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
await p.click('[data-act="edit"]'); await sleep(200); await setv('#fTarget', '24000'); await p.click('#goalSave'); await sleep(300);
ok('goal reaches 100% and shows done message', !!(await p.$('.done-line')));
await p.click('[data-act="delete"]'); await sleep(250);
await p.evaluate(() => { const c = document.querySelector('.card'); });
const left = (await p.$$('.card')).length; ok('delete (after confirm) removes the goal', left === 0);
ok('no console or page errors', errs.length === 0); if (errs.length) console.log(errs);
console.log(`${n - bad}/${n} passed`); await b.close(); process.exit(bad ? 1 : 0);
